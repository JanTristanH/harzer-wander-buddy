const { test, before } = require('node:test');
const assert = require('node:assert/strict');
const cds = require('@sap/cds');
const { linkIdentities } = require('../util/linkSupabaseIdentities');
const { resolveIdentity } = require('../srv/supabase-auth');
const { eraseMyData, isAccountDeleted, subjectHash, processAccountDeletions } = require('../srv/account-privacy');
let db;
const subject = 'b0eef491-e107-43c8-91a4-0ee12ee28ca5';
const row = { subject, internalId: 'auth0|legacy', proofReference: 'internal-case-1234-dual-account-proof' };
before(async () => { db = await cds.deploy('db/schema.cds').to('sqlite::memory:'); });
test('mapping dry-run, idempotence, collisions, stable references, deletion routing and replay guard', async () => {
  await db.run(cds.ql.INSERT.into('hwb.db.ExternalUsers').entries({ ID: row.internalId, name: 'Legacy' }));
  assert.equal((await db.tx(tx => linkIdentities(tx, [row]))).applied, false);
  assert.equal(await resolveIdentity(db, subject), `supabase|${subject}`);
  await db.tx(tx => linkIdentities(tx, [row], true));
  assert.equal(await resolveIdentity(db, subject), row.internalId);
  assert.equal((await db.tx(tx => linkIdentities(tx, [row], true))).existing, 1);
  await assert.rejects(db.tx(tx => linkIdentities(tx, [row, row], true)), /ambiguous/);
  await db.run(cds.ql.INSERT.into('hwb.db.ExternalUsers').entries({ ID: 'auth0|other', name: 'Other' }));
  await assert.rejects(db.tx(tx => linkIdentities(tx, [{ ...row, internalId: 'auth0|other' }], true)), /collision/);
  await db.tx(tx => eraseMyData(tx, row.internalId, true));
  assert.equal(await isAccountDeleted(row.internalId), true);
  await assert.rejects(resolveIdentity(db, subject), /Revoked/);
  const entry = await db.run(cds.ql.SELECT.one.from('hwb.db.AccountDeletions').where({ subjectHash: subjectHash(row.internalId) }));
  assert.equal(entry.provider, 'supabase'); assert.equal(entry.pendingSubject, subject);
  const legacyHash = subjectHash('auth0|old-deletion');
  await db.run(cds.ql.INSERT.into('hwb.db.AccountDeletions').entries({ subjectHash: legacyHash, pendingSubject: 'auth0|old-deletion', requestedAt: new Date().toISOString() }));
  const called = [];
  const result = await processAccountDeletions(async (id, provider) => { called.push([id, provider]); if (provider === 'supabase') throw new Error('Provider outage'); });
  assert.equal(result.failed, 1); assert.equal(result.processed, 1);
  assert.ok(called.some(([id, provider]) => id === 'auth0|old-deletion' && provider == null));
  assert.equal((await db.run(cds.ql.SELECT.one.from('hwb.db.AccountDeletions').where({ subjectHash: entry.subjectHash }))).pendingSubject, subject);
  assert.equal(await isAccountDeleted(row.internalId), true);
});
